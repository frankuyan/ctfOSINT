"""Markdown writeup generator for CTF competitions."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, TYPE_CHECKING

import re
from urllib.parse import quote, urlsplit

from jinja2 import Environment, BaseLoader

from sherlockml import __version__

if TYPE_CHECKING:
    from sherlockml.enum.orchestrator import SearchResults


# Most values in a writeup (page titles, bios, discovered usernames) come
# from pages the target controls.  Unescaped, ``![x](https://evil/p.png)``
# or ``<img src=...>`` would load from the target's server when the report
# is previewed, revealing the investigator's IP, and newlines or ``|`` could
# forge sections or table rows.
_MD_SPECIAL = re.compile(r"([\\`*_{}\[\]()<>#+!|~&])")
_MAX_FIELD_CHARS = 300


def md_text(value: Any) -> str:
    """Escape untrusted text for inline Markdown (one line, no HTML)."""
    text = " ".join(str(value).split())
    if len(text) > _MAX_FIELD_CHARS:
        text = text[:_MAX_FIELD_CHARS] + "..."
    return _MD_SPECIAL.sub(r"\\\1", text)


def md_code(value: Any) -> str:
    """Render untrusted text as an inline code span that can't be broken out of."""
    text = " ".join(str(value).split())
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if text.startswith("`") or text.endswith("`") or longest else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def md_url(value: Any) -> str:
    """Return an http(s) URL safe inside ``[text](...)``, or ``#``."""
    url = str(value or "")
    if urlsplit(url).scheme.lower() not in ("http", "https"):
        return "#"
    # Encode whitespace, parentheses, angle brackets and quotes
    return quote(url, safe=":/?#[]@!$&*+,;=%~-._'")


# Default writeup template
DEFAULT_TEMPLATE = """# OSINT Investigation: {{ target_username | md }}

**Generated:** {{ generated_at }}  
**Duration:** {{ elapsed_time }}s  
**Platforms Checked:** {{ total_platforms }}

---

## Summary

- **Profiles Found:** {{ found_count }}
- **Flags Discovered:** {{ flags_count }}
- **Success Rate:** {{ success_rate }}%

{% if flags %}
## 🚩 Flags Found

{% for flag in flags %}
- {{ flag | code }}
{% endfor %}
{% endif %}

{% if contacts %}
## Contacts

{% for email in contacts %}
- {{ email | code }}
{% endfor %}
{% endif %}

## Profile Results

| Platform | Username | URL | Confidence |
|----------|----------|-----|------------|
{% for result in top_results %}
| {{ result.platform | md }} | {{ result.username | md }} | [Link]({{ result.url | url }}) | {{ result.confidence }}% |
{% endfor %}

{% if metadata_highlights %}
## Notable Metadata

{% for item in metadata_highlights %}
### {{ item.platform | md }} - {{ item.username | md }}

{% for key, value in item.fields.items() %}
- **{{ key | md }}:** {{ value | md }}
{% endfor %}

{% endfor %}
{% endif %}

{% if variants_searched and variants_searched|length > 1 %}
## Username Variants Searched

{% for variant in variants_searched %}
- {{ variant | code }}
{% endfor %}
{% endif %}

---

*Generated by SherlockML v{{ version }}*
"""


class MarkdownWriter:
    """CTF writeup generator.
    
    Generates markdown summaries of search results for
    quick CTF write-ups and documentation.
    
    Example:
        >>> writer = MarkdownWriter()
        >>> markdown = writer.generate_writeup(results, flags)
        >>> writer.save(markdown, Path("writeup.md"))
    """
    
    def __init__(
        self,
        template: str | None = None,
        template_path: Path | str | None = None,
    ):
        """Initialize the writer.
        
        Args:
            template: Jinja2 template string
            template_path: Path to template file
        """
        self.env = Environment(loader=BaseLoader())
        # Filters for custom templates too: md (inline text), code (inline
        # code span) and url (link target)
        self.env.filters.update(md=md_text, code=md_code, url=md_url)
        
        if template_path:
            template_path = Path(template_path).expanduser()
            if template_path.exists():
                template = template_path.read_text()
        
        self.template = self.env.from_string(template or DEFAULT_TEMPLATE)
    
    def generate_writeup(
        self,
        results: "SearchResults",
        flags: list[str] | None = None,
        additional_context: dict[str, Any] | None = None,
    ) -> str:
        """Generate markdown summary for CTF writeup.
        
        Args:
            results: Search results
            flags: Optional list of discovered flags
            additional_context: Extra template variables
            
        Returns:
            Markdown formatted string
        """
        # Prepare top results
        found_results = [r for r in results.results if r.exists]
        top_results = sorted(found_results, key=lambda r: r.confidence, reverse=True)[:20]
        
        formatted_results = [
            {
                "platform": r.platform,
                "username": r.username,
                "url": r.url or "#",
                "confidence": round(r.confidence * 100),
            }
            for r in top_results
        ]
        
        # Extract metadata highlights
        metadata_highlights = []
        for r in top_results[:10]:
            if r.metadata and any(r.metadata.values()):
                meaningful_fields = {
                    k: v for k, v in r.metadata.items()
                    if v and k not in ('raw', 'headers') and not k.startswith('_')
                }
                if meaningful_fields:
                    metadata_highlights.append({
                        "platform": r.platform,
                        "username": r.username,
                        "fields": meaningful_fields,
                    })
        
        # Combine flags from results and explicit list
        all_flags = list(results.flags_found)
        if flags:
            all_flags.extend(f for f in flags if f not in all_flags)
        
        # Build template context
        context = {
            "target_username": results.query_username,
            "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
            "version": __version__,
            "contacts": results.contacts,
            "elapsed_time": round(results.elapsed_time, 2),
            "total_platforms": results.total_platforms,
            "found_count": results.found_count,
            "flags_count": len(all_flags),
            "success_rate": round(
                (results.successful_checks / max(1, results.total_platforms)) * 100, 1
            ),
            "flags": all_flags,
            "top_results": formatted_results,
            "metadata_highlights": metadata_highlights[:5],
            "variants_searched": results.variants_searched,
        }
        
        if additional_context:
            context.update(additional_context)
        
        return self.template.render(**context)
    
    def save(
        self,
        content: str,
        output_path: Path | str,
    ) -> None:
        """Save markdown to file.
        
        Args:
            content: Markdown content
            output_path: Output file path
        """
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(content)
    
    def generate_quick_summary(
        self,
        results: "SearchResults",
    ) -> str:
        """Generate a quick one-line summary.
        
        Args:
            results: Search results
            
        Returns:
            Brief summary string
        """
        return (
            f"Found {results.found_count} profiles for '{results.query_username}' "
            f"across {results.total_platforms} platforms in {results.elapsed_time:.1f}s. "
            f"Flags: {len(results.flags_found)}"
        )
    
    def generate_flags_json(
        self,
        results: "SearchResults",
        output_path: Path | str | None = None,
    ) -> dict[str, Any]:
        """Generate flags.json for team sharing.
        
        Args:
            results: Search results
            output_path: Optional path to save
            
        Returns:
            Flags dictionary
        """
        import json
        
        flags_data = {
            "generated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
            "target": results.query_username,
            "flags": [
                {
                    "flag": flag,
                    "source": "sherlockml",
                }
                for flag in results.flags_found
            ],
        }
        
        if output_path:
            output_path = Path(output_path)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            with open(output_path, "w") as f:
                json.dump(flags_data, f, indent=2)
        
        return flags_data
